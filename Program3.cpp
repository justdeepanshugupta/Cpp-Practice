#include <iostream>
using namespace std;
//This is my third program in which i use Relational Operators

int main() {
    cout << (4 < 5) << endl; //true->1
    cout << (4 > 5) << endl; //false->0
    cout << (4 >= 3) << endl; //true->1
    cout << (4 <= 3) << endl; //false->0
    cout << (4 != 3) << endl; //true->1
    cout << (4 != 4) << endl; //false->0
    cout << (4 == 4) << endl; //true->1

    return 0;
}